  user_id = auth.uid()
  and (
    (workspace_mode = 'community' and organization_id is null)
    or (workspace_mode = 'corporate' and organization_id is not null and private.is_org_member(organization_id))
  )
);
create policy "Users update own incidents" on public.incidents for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "Users read own support rows" on public.incident_support for select to authenticated using (user_id = auth.uid());

create policy "Authenticated users read allowed messages" on public.chat_messages for select to authenticated using (
  (workspace_mode = 'community' and status = 'published')
  or user_id = auth.uid()
  or (workspace_mode = 'corporate' and organization_id is not null and private.is_org_member(organization_id))
