-- Root Lounge v2 production schema
-- Run in a fresh Supabase project, then enable Anonymous Sign-Ins in Auth settings.

create extension if not exists pgcrypto;
create schema if not exists private;

create table if not exists public.user_metrics (
  user_id uuid primary key references auth.users(id) on delete cascade,
  sanity integer not null default 42 check (sanity between 0 and 100),
  caffeine integer not null default 78 check (caffeine between 0 and 100),
  sleep integer not null default 55 check (sleep between 0 and 100),
  hydration integer not null default 90 check (hydration between 0 and 100),
  updated_at timestamptz not null default now()
);

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 80),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table if not exists public.incidents (
  id uuid primary key default gen_random_uuid(),
  display_id text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  organization_id uuid references public.organizations(id) on delete cascade,
  workspace_mode text not null check (workspace_mode in ('community', 'corporate')),
  title text not null check (char_length(title) between 1 and 500),
  severity text not null default 'Venting' check (severity in ('Critical', 'Warning', 'Venting', 'Resolved')),
  status text not null default 'published' check (status in ('published', 'hidden', 'review')),
  support_count integer not null default 0 check (support_count >= 0),
  created_at timestamptz not null default now(),
  constraint corporate_incident_org check (
    (workspace_mode = 'community' and organization_id is null)
    or (workspace_mode = 'corporate' and organization_id is not null)
  )
);

create table if not exists public.incident_support (
  incident_id uuid not null references public.incidents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (incident_id, user_id)
);

create table if not exists public.chat_messages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  organization_id uuid references public.organizations(id) on delete cascade,
  workspace_mode text not null check (workspace_mode in ('community', 'corporate')),
  sender text not null check (char_length(sender) between 1 and 24),
  body text not null check (char_length(body) between 1 and 700),
  status text not null default 'published' check (status in ('published', 'hidden', 'review')),
  created_at timestamptz not null default now(),
  constraint corporate_message_org check (
    (workspace_mode = 'community' and organization_id is null)
    or (workspace_mode = 'corporate' and organization_id is not null)
  )
);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  stripe_event_id text not null unique,
  stripe_session_id text,
  event_type text not null,
  payment_status text,
  customer_id text,
  subscription_id text,
  root_lounge_user_id text,
  sku text,
  workspace_mode text,
  amount_total bigint,
  currency text,
  raw_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Defense-in-depth moderation. Client checks improve UX; these triggers prevent obvious
-- credential leaks, direct threats, and crisis phrases from being inserted by a modified client.
create or replace function private.assert_safe_lounge_text(candidate text)
returns void
language plpgsql
immutable
set search_path = pg_catalog
as $$
begin
  if candidate ~* '-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----'
     or candidate ~ '\mAKIA[0-9A-Z]{16}\M'
     or candidate ~* '\m(sk|rk)_(live|test)_[A-Za-z0-9]{16,}\M'
     or candidate ~* '\m(password|api[_ -]?key)\s*[:=]\s*\S+' then
    raise exception 'Remove passwords, keys, or credentials before posting.';
  end if;

  if candidate ~* '\m(kill myself|end my life|want to die|do not want to live|don''t want to live|suicid(e|al)|hurt myself|self[- ]harm)\M' then
    raise exception 'This message needs immediate live support rather than a public feed.';
  end if;

  if candidate ~* '\m(i am|i''m|i will) going to kill (him|her|them|you)\M'
     or candidate ~* '\mshoot (up|him|her|them|you)\M' then
    raise exception 'Direct threats cannot be posted.';
  end if;
end;
$$;

create or replace function private.moderate_incident_before_write()
returns trigger
language plpgsql
set search_path = public, private, pg_temp
as $$
begin
  perform private.assert_safe_lounge_text(new.title);
  return new;
end;
$$;

create or replace function private.moderate_message_before_write()
returns trigger
language plpgsql
set search_path = public, private, pg_temp
as $$
begin
  perform private.assert_safe_lounge_text(new.body);
  return new;
end;
$$;

drop trigger if exists moderate_incident_text on public.incidents;
create trigger moderate_incident_text before insert or update of title on public.incidents
for each row execute function private.moderate_incident_before_write();

drop trigger if exists moderate_chat_text on public.chat_messages;
create trigger moderate_chat_text before insert or update of body on public.chat_messages
for each row execute function private.moderate_message_before_write();

create or replace function private.is_org_member(target_org uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org and m.user_id = auth.uid()
  );
$$;

create or replace function private.is_org_owner(target_org uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org and m.user_id = auth.uid() and m.role in ('owner', 'admin')
  );
$$;

grant usage on schema private to authenticated;
grant execute on function private.is_org_member(uuid) to authenticated;
grant execute on function private.is_org_owner(uuid) to authenticated;

