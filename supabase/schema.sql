create or replace function public.support_incident(target_incident_id uuid)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_count integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;

  if not exists (
    select 1 from public.incidents i
    where i.id = target_incident_id
      and (
        (i.workspace_mode = 'community' and i.status = 'published')
        or i.user_id = auth.uid()
        or (i.workspace_mode = 'corporate' and i.organization_id is not null and private.is_org_member(i.organization_id))
      )
  ) then raise exception 'Incident is not accessible'; end if;

  insert into public.incident_support (incident_id, user_id)
  values (target_incident_id, auth.uid())
  on conflict do nothing;

  select count(*)::integer into new_count from public.incident_support where incident_id = target_incident_id;
  update public.incidents set support_count = new_count where id = target_incident_id;
  return new_count;
end;
$$;

grant execute on function public.support_incident(uuid) to authenticated;

-- Create an organization and automatically add its creator as owner.
create or replace function public.create_organization(org_name text)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_org_id uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  insert into public.organizations(name, created_by) values (org_name, auth.uid()) returning id into new_org_id;
  insert into public.organization_members(organization_id, user_id, role) values (new_org_id, auth.uid(), 'owner');
  return new_org_id;
end;
$$;

grant execute on function public.create_organization(text) to authenticated;

