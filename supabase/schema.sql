  private.is_org_owner(organization_id)
  or exists (select 1 from public.organizations o where o.id = organization_id and o.created_by = auth.uid())
);
create policy "Owners update memberships" on public.organization_members for update to authenticated using (private.is_org_owner(organization_id));
create policy "Owners delete memberships" on public.organization_members for delete to authenticated using (private.is_org_owner(organization_id));

create policy "Authenticated users read allowed incidents" on public.incidents for select to authenticated using (
  (workspace_mode = 'community' and status = 'published')
  or user_id = auth.uid()
  or (workspace_mode = 'corporate' and organization_id is not null and private.is_org_member(organization_id))
);
